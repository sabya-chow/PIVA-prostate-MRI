"""Writer checks for abstract_v4 (read-only on analysis/). Run in conda env pvae:
    conda run -n pvae python checks_v4.py > checks_v4_output.txt
Verifies reviewer-quoted numbers from analysis/preds/*.npz, analysis/results/*.csv,
with truths regenerated by analysis/piva_core.build_test_cohort('large2000').
"""
import sys
import numpy as np
import pandas as pd
from scipy.stats import spearmanr

A = str(__import__("pathlib").Path(__file__).resolve().parents[1] / "analysis")
sys.path.insert(0, A)
import piva_core as pc  # noqa: E402

P = ["D_ep", "D_st", "D_lum", "T2_ep", "T2_st", "T2_lum", "v_ep", "v_st", "v_lum"]
LO = np.r_[pc.D_MEAN_3 - pc.D_DELTA_3, pc.T2_MEAN_3 - pc.T2_DELTA_3, np.zeros(3)]
HI = np.r_[pc.D_MEAN_3 + pc.D_DELTA_3, pc.T2_MEAN_3 + pc.T2_DELTA_3, np.ones(3)]
R = pc.FULL_RANGE
y = pc.build_test_cohort("large2000")["y"]
cal = pd.read_csv(f"{A}/results/calibration_long.csv")
L = cal[cal.cohort == "large2000"]


def load(tag, seed, sig):
    d = np.load(f"{A}/preds/{tag}_s{seed}_large2000_sig{sig}.npz")
    return d["mean"], d["sd"]


def widths(m, s, tau=1.0):
    lo, hi = m - 1.96 * tau * s, m + 1.96 * tau * s
    cov = ((y >= lo) & (y <= hi)).mean(0)
    raw = 100 * (hi - lo).mean(0) / R
    clo, chi = np.maximum(lo, LO), np.minimum(hi, HI)
    clip = 100 * (chi - clo).mean(0) / R
    outside = ((lo < LO) | (hi > HI)).mean(0)
    return cov, raw, clip, outside


def show(title, arr, fmt="{:.2f}"):
    print(title.ljust(52), " ".join(fmt.format(a).rjust(6) for a in arr))


print("params".ljust(52), " ".join(p.rjust(6) for p in P))

# 1. Clipped vs unclipped calibrated widths (sep-cohort tau, per seed, mean over seeds)
print("\n# 1. Calibrated (separate-cohort tau) widths, sigma=0.05, mean of 3 seeds")
for tag, name in [("chol", "PIVA-CholeskyILR"), ("diag", "PIVA-Diagonal")]:
    acc = []
    for s in range(3):
        m, sd = load(tag, s, 0.05)
        tau = L[(L.model == name) & (L.seed == s) & (L.sigma == 0.05)].set_index("param").loc[P, "sep_tau"].values
        acc.append(widths(m, sd, tau))
    acc = np.array(acc).mean(0)
    show(f"{tag} cal coverage", acc[0])
    show(f"{tag} cal width unclipped %", acc[1], "{:.0f}")
    show(f"{tag} cal width clipped %", acc[2], "{:.0f}")
    show(f"{tag} frac voxels interval leaves box", acc[3])

# 2. SD-50 likelihood (seed 0) across sigma: raw coverage, widths, clipped
print("\n# 2. Likelihood SD 50, seed 0, raw (no tau)")
for tag in ["gen-chol-ilr-gauss50-clean", "gen-chol-ilr-gauss50-noisy", "gen-chol-ilr-rician50-noisy",
            "gen-diag-softmax-gauss50-clean"]:
    for sig in [0.01, 0.03, 0.05, 0.08]:
        m, sd = load(tag, 0, sig)
        c, w, wc, _ = widths(m, sd)
        show(f"{tag} s={sig} cov", c)
        show(f"{tag} s={sig} width unclipped", w, "{:.0f}")
        show(f"{tag} s={sig} width clipped", wc, "{:.0f}")
    rho = [spearmanr(sd[:, j], np.abs(m[:, j] - y[:, j]))[0] for j in range(9)]
    show(f"{tag} s=0.08 spearman rho (last sigma)", rho)
    m, sd = load(tag, 0, 0.05)
    rho = [spearmanr(sd[:, j], np.abs(m[:, j] - y[:, j]))[0] for j in range(9)]
    show(f"{tag} s=0.05 spearman rho", rho)

# 3. Original-loss coverage vs sigma (3-seed mean, from CSV)
print("\n# 3. Original loss raw coverage vs sigma (calibration_long, mean over seeds)")
for name in ["PIVA-Diagonal", "PIVA-CholeskyILR"]:
    for sig in [0.01, 0.03, 0.05, 0.08]:
        t = L[(L.model == name) & (L.sigma == sig)].groupby("param").raw_cov.mean().loc[P].values
        show(f"{name} s={sig}", t)

# 4. BCRB: shrinkage, prior-free CRB width, max achievable R2
print("\n# 4. crb_widths.csv, sigma=0.05")
crb = pd.read_csv(f"{A}/results/crb_widths.csv")
c5 = crb[crb.sigma == 0.05].set_index("param").loc[P]
show("shrink ratio (BCRB/prior SD)", c5.shrink_ratio_bcrb_rician_full.values, "{:.3f}")
show("shrinkage % = 100(1-ratio)", 100 * (1 - c5.shrink_ratio_bcrb_rician_full.values), "{:.1f}")
show("max R2 = 1 - ratio^2", 1 - c5.shrink_ratio_bcrb_rician_full.values ** 2)
show("prior-free CRB 95% width % box", c5.crb_rician_noprior_pct.values, "{:.0f}")
show("BCRB 95% width %", c5.bcrb_rician_expectedF_fullprior_pct.values, "{:.1f}")
for sig in [0.01, 0.03, 0.08]:
    show(f"BCRB width % sigma={sig}", crb[crb.sigma == sig].set_index("param").loc[P].bcrb_rician_expectedF_fullprior_pct.values, "{:.1f}")

# 5. Epithelium fraction: contrast compression and voxel-level exclusion
print("\n# 5. v_ep by true composition (benign-like 0.18-0.28, cancer-like 0.44-0.54), sigma=0.05")
ve = y[:, 6]
ben, can = (ve > 0.18) & (ve < 0.28), (ve > 0.44) & (ve < 0.54)
print(f"n benign-like {ben.sum()}, cancer-like {can.sum()}; true means {ve[ben].mean():.3f} {ve[can].mean():.3f}")
for tag, seeds in [("chol", [0, 1, 2]), ("diag", [0, 1, 2]), ("gen-chol-ilr-gauss50-clean", [0]),
                   ("gen-chol-ilr-gauss50-noisy", [0]), ("gen-chol-ilr-rician50-noisy", [0])]:
    for s in seeds:
        m, sd = load(tag, s, 0.05)
        lo, hi = m[:, 6] - 1.96 * sd[:, 6], m[:, 6] + 1.96 * sd[:, 6]
        print(f"{tag} s{s}: est mean benign {m[ben,6].mean():.3f} cancer {m[can,6].mean():.3f} "
              f"(contrast {m[can,6].mean()-m[ben,6].mean():.3f}); cancer-like cov {((ve[can]>=lo[can])&(ve[can]<=hi[can])).mean():.2f}, "
              f"excl 0.232 {((lo[can]>0.232)|(hi[can]<0.232)).mean():.2f}; benign-like excl 0.488 {((lo[ben]>0.488)|(hi[ben]<0.488)).mean():.2f}; "
              f"mean halfwidth cancer {1.96*sd[can,6].mean():.3f}")
# stratified coverage
for tag, seeds in [("chol", [0, 1, 2]), ("gen-chol-ilr-gauss50-clean", [0]), ("gen-chol-ilr-gauss50-noisy", [0])]:
    for s in seeds:
        m, sd = load(tag, s, 0.05)
        lo, hi = m[:, 6] - 1.96 * sd[:, 6], m[:, 6] + 1.96 * sd[:, 6]
        cov = (ve >= lo) & (ve <= hi)
        bins = [(ve < 0.3), (ve >= 0.3) & (ve <= 0.4), (ve > 0.4)]
        print(f"{tag} s{s} v_ep cov by bin <0.3/0.3-0.4/>0.4: " + " ".join(f"{cov[b].mean():.2f}(n={b.sum()},bias {(m[b,6]-ve[b]).mean():+.2f})" for b in bins))

# 6. Fig 5 spread across networks (summary_mean_sd)
print("\n# 6. v R2 spread across PIA / Diagonal / Cholesky (large2000)")
sm = pd.read_csv(f"{A}/results/summary_mean_sd.csv")
for sig in [0.01, 0.03, 0.05, 0.08]:
    row = []
    for p in ["v_ep", "v_st", "v_lum"]:
        q = sm[(sm.cohort == "large2000") & (sm.sigma == sig) & (sm.metric == f"{p}_R2") & sm.model.isin(["PIA", "PIVA-Diagonal", "PIVA-CholeskyILR"])]
        row.append(f"{p}: " + " ".join(f"{r.model[:9]}={r['mean']:.3f}" for _, r in q.iterrows()) + f" spread={q['mean'].max()-q['mean'].min():.3f}")
    print(f"sigma={sig}: " + " | ".join(row))
